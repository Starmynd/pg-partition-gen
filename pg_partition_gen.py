#!/usr/bin/env python3
"""pg-partition-gen - generate PostgreSQL declarative range partition DDL
for tables keyed by a date or timestamp column.

Outputs a CREATE TABLE ... PARTITION BY RANGE (...) header, one partition per
period (day/month/year) over the requested date span with aligned boundaries,
plus a DEFAULT partition.
"""

from __future__ import annotations

import argparse
import sys
from datetime import date


class InputError(ValueError):
    pass


def align_start(d: date, period: str) -> date:
    if period == "month":
        return d.replace(day=1)
    if period == "year":
        return d.replace(month=1, day=1)
    return d


def period_bounds(start: date, period: str) -> tuple[date, date]:
    """Return [from, to) boundaries of the period containing `start`."""
    if period == "day":
        nxt = date.fromordinal(start.toordinal() + 1)
        return start, nxt
    if period == "month":
        y, m = start.year, start.month
        if m == 12:
            nxt = date(y + 1, 1, 1)
        else:
            nxt = date(y, m + 1, 1)
        return start.replace(day=1), nxt
    if period == "year":
        return date(start.year, 1, 1), date(start.year + 1, 1, 1)
    raise InputError(f"unknown period: {period}")


def advance(d: date, period: str) -> date:
    if period == "day":
        return date.fromordinal(d.toordinal() + 1)
    if period == "month":
        return date(d.year + (1 if d.month == 12 else 0),
                    1 if d.month == 12 else d.month + 1, 1)
    if period == "year":
        return date(d.year + 1, 1, 1)
    raise InputError(f"unknown period: {period}")


def suffix(d: date, period: str) -> str:
    if period == "day":
        return f"{d.year}_{d.month:02d}_{d.day:02d}"
    if period == "month":
        return f"{d.year}_{d.month:02d}"
    return str(d.year)


PARTITION_LIMITS = {"day": 1000, "month": 120, "year": 30}


def count_partitions(start: date, end: date, period: str) -> int:
    if period == "day":
        return (end - start).days + 1
    if period == "month":
        return (end.year - start.year) * 12 + end.month - start.month + 1
    return end.year - start.year + 1


def validate(table: str, column: str, start: date, end: date, period: str) -> None:
    if not table or not column:
        raise InputError("table and column must be non-empty")
    if period not in ("day", "month", "year"):
        raise InputError("period must be one of: day, month, year")
    if start > end:
        raise InputError("start date is after end date")
    n = count_partitions(start, end, period)
    if n > PARTITION_LIMITS[period]:
        raise InputError(
            f"span produces {n} partitions (limit {PARTITION_LIMITS[period]})")


def quote_ident(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def generate(table: str, column: str, start: date, end: date, period: str,
             schema: str | None = None) -> str:
    validate(table, column, start, end, period)
    q_table = quote_ident(table)
    q_col = quote_ident(column)
    prefix = f"{quote_ident(schema)}." if schema else ""
    lines: list[str] = []
    lines.append(f"-- Generated by pg-partition-gen ({period} partitions)")
    lines.append("-- The tool does not introspect your schema: review and fill in")
    lines.append("-- the column list before running this DDL.")
    lines.append(f"CREATE TABLE IF NOT EXISTS {prefix}{q_table} (")
    lines.append(f"    -- id         bigint GENERATED ALWAYS AS IDENTITY,")
    lines.append(f"    -- {column:<10} timestamptz NOT NULL")
    lines.append(f") PARTITION BY RANGE ({q_col});")
    lines.append("")

    cur = align_start(start, period)
    while cur <= end:
        lo, hi = period_bounds(cur, period)
        name = f"{table}_{suffix(cur, period)}"
        lines.append(
            f"CREATE TABLE IF NOT EXISTS {prefix}{quote_ident(name)} "
            f"PARTITION OF {prefix}{q_table} "
            f"FOR VALUES FROM ('{lo.isoformat()}') TO ('{hi.isoformat()}');"
        )
        cur = advance(cur, period)

    lines.append("")
    lines.append(
        f"CREATE TABLE IF NOT EXISTS {prefix}{quote_ident(table + '_default')} "
        f"PARTITION OF {prefix}{q_table} DEFAULT;"
    )
    return "\n".join(lines) + "\n"


def _selftest() -> int:
    failed = 0

    def check(cond: bool, label: str) -> None:
        nonlocal failed
        print(("PASS " if cond else "FAIL ") + label)
        if not cond:
            failed += 1

    sql = generate("events", "created_at",
                   date(2026, 1, 1), date(2026, 3, 31), "month")
    parts = [ln for ln in sql.splitlines() if "PARTITION OF" in ln and "DEFAULT" not in ln]
    check(len(parts) == 3, f"three monthly partitions (got {len(parts)})")
    check("FOR VALUES FROM ('2026-01-01') TO ('2026-02-01')" in sql,
          "first boundary text")
    check("FOR VALUES FROM ('2026-03-01') TO ('2026-04-01')" in sql,
          "last boundary text")
    check("PARTITION BY RANGE (\"created_at\")" in sql, "partition by column")
    check("events_default" in sql and "DEFAULT;" in sql, "default partition")
    check("CREATE TABLE IF NOT EXISTS \"events\" (" in sql, "header present")

    sql_d = generate("t", "d", date(2026, 2, 27), date(2026, 3, 2), "day")
    check(sql_d.count("PARTITION OF") - ("DEFAULT" in sql_d) == 4,
          "day span crosses month: 4 daily partitions")
    check("FROM ('2026-02-28') TO ('2026-03-01')" in sql_d, "non-leap Feb 28 boundary")

    sql_y = generate("t", "d", date(2025, 6, 1), date(2027, 1, 1), "year")
    check(sql_y.count("t_2025") == 1 and sql_y.count("t_2026") == 1
          and sql_y.count("t_2027") == 1, "year partitions aligned to Jan 1")

    for bad_args in [dict(table="", column="c", start=date(2026, 1, 1),
                          end=date(2026, 2, 1), period="month"),
                     dict(table="t", column="c", start=date(2027, 1, 1),
                          end=date(2026, 1, 1), period="month"),
                     dict(table="t", column="c", start=date(1950, 1, 1),
                          end=date(2026, 1, 1), period="year")]:
        try:
            generate(**bad_args)
            check(False, f"rejects {bad_args}")
        except InputError:
            check(True, f"rejects bad input #{sorted(bad_args)[0]}")

    print(f"selftest: failures={failed}")
    return 1 if failed else 0


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if "--test" in argv:
        return _selftest()

    ap = argparse.ArgumentParser(
        prog="pg-partition-gen",
        description="Generate PostgreSQL range partition DDL for date-keyed tables.",
    )
    ap.add_argument("--table", required=True)
    ap.add_argument("--column", required=True, help="date/timestamp partition key")
    ap.add_argument("--start", required=True, help="YYYY-MM-DD")
    ap.add_argument("--end", required=True, help="YYYY-MM-DD")
    ap.add_argument("--period", choices=["day", "month", "year"], default="month")
    ap.add_argument("--schema", help="optional schema qualifier")
    ap.add_argument("--out", help="write to file instead of stdout")
    args = ap.parse_args(argv)

    try:
        start = date.fromisoformat(args.start)
        end = date.fromisoformat(args.end)
        sql = generate(args.table, args.column, start, end, args.period, args.schema)
    except (InputError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if args.out:
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(sql)
        print(f"written: {args.out}")
    else:
        sys.stdout.write(sql)
    return 0


if __name__ == "__main__":
    sys.exit(main())
